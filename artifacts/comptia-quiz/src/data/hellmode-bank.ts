function buildBank(): Question[] {
  const selectedFamilies = (["A+", "Network+", "Security+"] as const).flatMap((category) =>
    families.filter((family) => family.category === category).slice(0, 15),
  );
  const bank = selectedFamilies.flatMap((family, familyIndex) =>
    family.cases.map((scenario, caseIndex) => ({
      id: 30_000 + familyIndex * 6 + caseIndex,
      category: family.category,
      question: `${family.setup} ${scenario.evidence} ${family.ask}`,
      options: [...family.options],
      correctIndex: scenario.answer,
      explanation: family.explanations[scenario.answer],
      difficulty: "hard" as const,
    })),
  );
  validateBank(bank);
  return bank;
}

function validateBank(bank: Question[]): void {
  const categoryCounts: Record<ExamCategory, number> = { "A+": 0, "Network+": 0, "Security+": 0 };
  const ids = new Set<number>();
  const prompts = new Set<string>();
  const promptPadding = /hellmode case|account for .* before answering|select the single answer|before answering|based on the answer choices/i;
  const acronymRecall = /what does .+ stand for|what is .+ an acronym for|full meaning|full form|abbreviation/i;

  for (const question of bank) {
    categoryCounts[question.category]++;
    if (typeof question.id !== "number" || ids.has(question.id)) throw new Error("HellMode question IDs must be unique numbers.");
    ids.add(question.id);
    if (prompts.has(question.question)) throw new Error(`Duplicate HellMode prompt: ${question.id}`);
    prompts.add(question.question);
    if (question.difficulty !== "hard") throw new Error(`HellMode question ${question.id} is not hard-scored.`);
    if (question.options.length !== 4 || new Set(question.options).size !== 4) {
      throw new Error(`HellMode question ${question.id} must have four distinct choices.`);
    }
    if (!Number.isInteger(question.correctIndex) || question.correctIndex < 0 || question.correctIndex > 3) {
      throw new Error(`HellMode question ${question.id} has an invalid answer index.`);
    }
    if (question.question.length < 120 || !question.question.trim().endsWith("?")) {
      throw new Error(`HellMode question ${question.id} is missing a technical scenario or direct question.`);
    }
    if (promptPadding.test(question.question) || acronymRecall.test(question.question)) {
      throw new Error(`HellMode question ${question.id} contains padding or acronym-recall wording.`);
    }
  }

  if (bank.length !== 270 || categoryCounts["A+"] !== 90 || categoryCounts["Network+"] !== 90 || categoryCounts["Security+"] !== 90) {
    throw new Error(`HellMode bank must contain 270 questions balanced at 90 per exam; received ${JSON.stringify(categoryCounts)}.`);
  }
}

const hellModeBank = buildBank();

export function getHellModeQuestionBank(): Question[] {
  return hellModeBank;
}
